import re as _re


def _peak_of(path):
    pts = _re.findall(r'(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)', path)
    pairs = [(float(x), float(y)) for x, y in pts]
    px, py = min(pairs, key=lambda p: p[1])
    return (int(px), int(py))


