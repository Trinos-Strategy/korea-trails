def seg(no, title, km, time, body, bar, kind, tip_text):
    tip = (f'<div class="{kind}"><svg class="icon-svg"><use href="{IC}#icon-{"warning" if kind=="warn" else "tip"}"></use></svg> {tip_text}</div>')
