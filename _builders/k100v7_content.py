def mk_segs(items, ko):
    out = []
    for (no, t, km, tm, b, bar, kind, tip) in items:
        out.append((no, t[0 if ko else 1], km, tm, b[0 if ko else 1], bar, kind, tip[0 if ko else 1]))
    return out


def mk_cps(items, ko):
    return [(nm[0 if ko else 1], bd[0 if ko else 1], cls, alt, km, am[0 if ko else 1]) for (nm, bd, cls, alt, km, am) in items]


def mk_tips(items, ko):
    return [(ic, t[0 if ko else 1], [x[0 if ko else 1] for x in lst]) for (ic, t, lst) in items]


